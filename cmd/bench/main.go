func printRow(r levelResult) {
	rho := "  n/a"
	if r.Rho != nil {
		rho = fmt.Sprintf("%5.2f", *r.Rho)
	}
	drain := fmt.Sprintf("%8.2f", r.DrainSeconds)
	if !r.Drained {
		drain = fmt.Sprintf("%7.0f!", r.DrainSeconds)
	}
	fmt.Printf("%7d | %12.1f | %6.1f /%6.1f | %12.1f | %11d | %s | %15.1f | %6.0f /%6.0f | %s\n",
		r.Workers, r.InsertOpsPerS, r.InsertP50Ms, r.InsertP99Ms, r.LeaderOpsPerS, r.BacklogAtEnd, drain,
		r.SustainedOpsPerS, r.E2EP50Ms, r.E2EP99Ms, rho)
}

func printFooter(rep report) {
	best := 0.0
	for _, l := range rep.Levels {
		best = math.Max(best, l.SustainedOpsPerS)
	}
	fmt.Println()
	if rep.GroupSize > 1 {
		fmt.Printf("peak sustained: %.0f ops/s = %.0f groups/s (group size %d)\n", best, best/float64(rep.GroupSize), rep.GroupSize)
	} else {
		fmt.Printf("peak sustained: %.0f ops/s\n", best)
	}
	for _, l := range rep.Levels {
		extras := []string{}
		for status, n := range l.Statuses {
			if status != "CONFIRMED" {
				extras = append(extras, fmt.Sprintf("%s=%d", status, n))
			}
		}
		if l.InsertErrors > 0 {
			extras = append(extras, fmt.Sprintf("insert_errors=%d", l.InsertErrors))
		}
		if !l.Drained {
			extras = append(extras, "drain timed out (! above)")
		}
		if len(extras) > 0 {
			sort.Strings(extras)
			fmt.Printf("workers=%d: %s\n", l.Workers, strings.Join(extras, ", "))
		}
	}
	fmt.Println("columns: insert = what the inserters committed; leader = decided while inserts ran; sustained = ops / (window + drain);")
	fmt.Println("         e2e = registered_at -> confirmed_at on the DB clock; rho = leader busy time / (window + drain), 1.0 = saturated.")
}

func writeJSON(path string, rep report) error {
	b, err := json.MarshalIndent(rep, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0o644)
}

// dropSchema removes a generated schema on its own short-lived connection.
func dropSchema(ctx context.Context, url, schema string) error {
	pool, err := pgxpool.New(ctx, url)
	if err != nil {
		return err
	}
	defer pool.Close()
	_, err = pool.Exec(ctx, "DROP SCHEMA IF EXISTS "+pgx.Identifier{schema}.Sanitize()+" CASCADE")
	return err
}

func sleepCtx(ctx context.Context, d time.Duration) error {
	t := time.NewTimer(d)
	defer t.Stop()
	select {
	case <-ctx.Done():
		return ctx.Err()
	case <-t.C:
		return nil
	}
}
