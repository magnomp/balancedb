// Command bench measures how many operations per second one BalanceDB cell
// sustains end to end: registrations committed by concurrent inserters AND
// decided by the single elected leader.
//
// It runs directly against Postgres through the same insertion core the HTTP api
// uses (internal/ledger) and the same processor the `processor` role runs, so the
// numbers are the cell's ceiling with no HTTP in the way (spec §14: "the cell's
// database bounds throughput"). Add an api node in front with `make loadgen` when
// you want the HTTP-inclusive figure.
//
// For each worker count in -workers it runs a warmup, waits for the leader to drain
// the backlog, then measures a fixed insertion window with closed-loop inserters
// (each worker: BEGIN → Insert → COMMIT, repeat), stops, and waits for the leader to
// drain again. It reports both sides of the system per level:
//
//   - insertion: ops/s and registrations/s committed, client-observed commit latency;
//   - the leader: ops/s decided while inserts were running, backlog at the end of the
//     window, time to drain it, and the sustained rate = ops / (window + drain) —
//     the honest "what the cell can hold" number when the backlog grows;
//   - end-to-end latency (registered_at → confirmed_at, both DB clock) percentiles;
//   - loop utilization ρ (spec §13), the capacity signal: 0.4 at 800 ops/s means the
//     leader has room for ~2,000 ops/s before the backlog starts to grow.
//
// Amounts are positive against unbounded accounts, so every operation is accepted —
// the point is throughput, not validation. It is a developer tool, not part of any
// deployed binary; it never touches a schema you did not name unless it created it.
package main

